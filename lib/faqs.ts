export function getFaqs(path: string): readonly FaqItem[] {
  const items = faqsByPath[path as keyof typeof faqsByPath];

  if (!items) {
    throw new Error(`Для страницы ${path} не подготовлен блок частых вопросов`);
  }

  return items;
}

export function getFaqJsonLd(path: string, items: readonly FaqItem[]) {
  const pageUrl = new URL(path, `${siteUrl}/`).toString();

  return {
    "@type": "FAQPage",
    "@id": `${pageUrl}#faq`,
    url: pageUrl,
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.answer,
      },
    })),
  };
}
